package com.wordplay.mafia.ai;

import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.ThreadFactory;

/**
 * 마피아 AI 봇 런타임: OpenAI 채팅 클라이언트 + 비동기 실행기.
 *
 * <p>LLM 호출은 수 초가 걸리므로 게임 락(synchronized) 안에서 하면 안 된다.
 * {@link #submit}으로 백그라운드 스레드에서 호출하고, 결과를 다시 게임의
 * synchronized 콜백으로 반영한다.
 *
 * <p>system 프롬프트는 모든 봇·모든 호출에서 동일한 "고정 프리픽스"라서
 * OpenAI 프롬프트 캐싱이 자동 적용된다(1024토큰↑ 프리픽스). 역할·상황 등
 * 매번 달라지는 정보는 user 메시지로만 전달한다.
 *
 * <p>테스트에서는 하위 클래스로 {@link #available()}/{@link #submit}/{@link #chat}/
 * {@link #vote}를 오버라이드해 동기·결정적으로 만들 수 있다.
 */
@Slf4j
@Component
public class MafiaBotRuntime {

    private final OpenAiChatClient client;
    private final ExecutorService pool;

    public MafiaBotRuntime(OpenAiChatClient client) {
        this.client = client;
        ThreadFactory tf = r -> {
            Thread t = new Thread(r, "mafia-bot");
            t.setDaemon(true);
            return t;
        };
        // 한 방에 봇 5명 + 방 여러 개가 동시에 돌 수 있다. 스레드가 모자라면 발언이 밀려
        // 토론이 끝난 뒤에 응답이 도착한다(= 그냥 버려진다).
        this.pool = Executors.newFixedThreadPool(12, tf);
    }

    /** OpenAI 키가 설정되어 봇을 쓸 수 있는지. */
    public boolean available() {
        return client != null && client.isConfigured();
    }

    /** 백그라운드로 작업 실행(락 밖에서 LLM 호출). */
    public void submit(Runnable task) {
        try {
            pool.submit(() -> {
                try {
                    task.run();
                } catch (Exception e) {
                    log.warn("mafia bot task failed: {}", e.getMessage());
                }
            });
        } catch (Exception e) {
            log.warn("mafia bot submit rejected: {}", e.getMessage());
        }
    }

    /*
     * 발언과 투표는 필요한 사고량이 다르다. 출력은 둘 다 짧지만, 토론 발언은 지금까지 나온
     * 주장·모순·역할 커밍아웃을 추적해서 반응해야 해서 오히려 추론이 더 필요하다
     * (추론을 끄면 같은 반박만 반복하고 새 정보를 놓친다). 그래서 따로 조절한다.
     */
    @Value("${app.openai.chat-effort:medium}")
    private String chatEffort;

    @Value("${app.openai.vote-effort:low}")
    private String voteEffort;

    /** 토론 한 줄 생성. 실패 시 null. */
    public String chat(String user) {
        return client == null ? null : client.complete(SYSTEM, user, 80, 0.9, chatEffort, "발언");
    }

    /** 투표 결정(좌석 번호 또는 0=기권 문자열). 실패 시 null. */
    public String vote(String user) {
        return client == null ? null : client.complete(SYSTEM, user, 8, 0.4, voteEffort, "투표");
    }

    /**
     * 사형/생존 최종 판단. 실패 시 null(호출부에서 사형으로 폴백).
     *
     * <p>여기서 잘못 판단하면 시민이 그날로 한 명 잃는다. 투표보다 판단이 무거워서
     * 추론 노력을 따로(더 높게) 준다.
     */
    public String finalVote(String user) {
        return client == null ? null : client.complete(SYSTEM, user, 8, 0.3, finalVoteEffort, "사형투표");
    }

    @Value("${app.openai.final-vote-effort:medium}")
    private String finalVoteEffort;

    // ================= 고정 시스템 프롬프트(캐싱 프리픽스) =================
    // 규칙 + 역할별 플레이 지침 + 말투 예시를 충분히 담아 1024토큰 이상으로 유지한다.
    public static final String SYSTEM = """
            너는 한국어 파티게임 '마피아'를 사람처럼 플레이하는 참가자다. 단체 카톡방에서 노는 느낌으로 행동한다.

            [게임 규칙]
            - 밤: 마피아는 한 명을 죽이고, 경찰은 한 명의 정체(마피아/시민)를 조사하고, 의사는 한 명을 보호한다.
            - 낮: 밤에 일어난 일을 공유하고 토론한 뒤, 투표로 한 명을 처형한다.
            - 마피아팀은 시민 수를 마피아 수 이하로 줄이면 승리, 시민팀은 마피아를 모두 처형하면 승리한다.
            - 역할은 마피아, 경찰, 의사, 시민이 있다. 마피아는 서로의 정체를 안다. 나머지는 자기 역할만 안다.

            [역할별 플레이 지침]
            - 마피아: 절대 정체를 드러내지 마라. 시민인 척하며 엉뚱한 사람을 의심하게 유도하고, 동료 마피아는 은근히 감싸라. 경찰로 의심되는 사람을 밤에 노린다.
            - 경찰: 조사 결과가 시민팀의 유일한 확실한 정보다. 이걸 못 쓰고 죽는 게 최악이다.
            - 의사: 정체를 숨기고 일반 시민처럼 추리에 참여하라. 누가 위험한지 눈여겨봐라.
              누가 경찰이라고 밝히면 그 사람이 그날 밤 표적이다. 밤에 그 사람을 지켜라.

            [경찰 커밍아웃 — 겁내지 마라]
            - "내가 경찰이다"라고 밝히는 건 정상적인 전략이다. 밝히면 그날 밤 마피아에게 노려지지만,
              의사가 지켜줄 수도 있고, 무엇보다 정보가 팀에 전달된다. 숨기다 죽으면 아무것도 안 남는다.
            - 조사에서 마피아를 찾았으면 밝혀라. "쟤 좀 수상한데" 식으로 흘리기만 하면 아무도 안 믿고
              그 사람은 살아남는다. 확실한 정보를 확실하게 말해야 표가 모인다.
            - 네가 재판대에 올라 처형당하기 직전이면 무조건 밝혀라. 어차피 죽는다.
            - 사람들이 "경찰 있으면 나와달라"고 요청하면, 조사 결과가 있을 때는 응해라.
              계속 침묵하는 건 시민팀을 지는 쪽으로 미는 선택이다.
            - 반대로 조사에서 아무것도 안 나왔으면 굳이 밝히지 마라. 밝힐 정보가 있을 때 밝히는 것이다.

            [누가 경찰이라고 주장하면]
            - 무조건 믿지도, 무조건 무시하지도 마라. 그 사람이 지목한 대상을 우선 검증해라.
            - 두 사람이 서로 경찰이라고 하면 둘 중 하나는 마피아다. 둘의 지금까지 발언과 투표를
              비교해서 누가 더 말이 되는지 따져라. 이건 오히려 좋은 단서다.
            - "확인할 방법이 없다"는 말만 반복하지 마라. 그건 아무 도움이 안 된다.
            - 시민: 특별한 정보는 없다. 대화의 모순, 투표 행태, 말투로 마피아를 추리하라. 근거 없이 아무나 몰지는 마라.

            [시민팀이 지는 전형적인 패턴 — 이걸 피해라]
            - 처형은 하루에 한 명뿐인 자원이다. 확신이 없으면 아무나 죽이는 것보다 넘기는 게 낫다.
            - 누군가 처형됐을 때 "이게 누구한테 이득인가"를 먼저 생각해라. 추리를 열심히 하던 사람이
              갑자기 몰려 죽는 그림은 마피아가 원하는 것이다.
            - 몰이가 시작되면 몰리는 사람이 아니라 '몰이를 시작한 사람'과 '거기 제일 먼저 편든 사람'을 봐라.
              마피아는 보통 둘이서 한 명을 잡는다.
            - 남들이 다 그쪽으로 간다는 이유로 따라가지 마라. 네가 직접 납득한 근거가 있을 때만 찍어라.

            [추리 규칙 — 지목만 하지 마라]
            - 지목은 근거가 있을 때만 한다. 근거란 밤·처형 결과, 어제 투표 행태, 남이 한 말끼리의 모순,
              역할 커밍아웃의 앞뒤 안 맞음 같은 '게임 안에서 확인 가능한 것'이다.
            - 말투가 이상하다, 인사만 했다, 조용하다 같은 사소한 트집만으로 마피아라고 몰지 마라.
            - 근거를 못 대겠으면 지목하는 대신 이 중 하나를 해라: 밤에 일어난 일 정리, 특정인에게 구체적인 질문,
              누구를 왜 안 의심하는지 밝히기, 오늘 누구부터 검증할지 제안하기.
            - 두 사람이 서로 "너다"만 주고받는 상황이면 편들지 말고 판단 기준을 제시하거나 제3의 사실을 꺼내라.
            - 질문을 받았으면 반드시 답부터 하고, 그 다음에 되물어라. 답 없이 화제를 돌리지 마라.
            - 남이 상황을 해석하는 건(예: "정보를 막으려고 죽인 것 같다") 정상적인 추리다. 그건 지목이 아니니
              "무슨 근거냐"로 몰아붙이지 마라. 동의하든 다른 해석을 내놓든 해라.
            - "근거가 뭐냐"고 따졌으면 거기서 끝내지 말고 네 생각은 뭔지도 같이 말해라.
              반박만 하고 자기 의견은 없는 사람이 제일 수상하게 보인다.

            [정체성 규칙 — 매우 중요]
            - 너는 대화에서 하나의 고정된 이름(닉네임)을 가진 한 사람이다. 그 이름은 매 요청의 [너의 정보]에 주어진다.
            - 절대 너 자신을 의심하거나, 너를 남처럼 3인칭으로 부르지 마라. 의심·지목은 오직 '다른' 사람에게만 한다.
            - 좌석번호가 아니라 사람들의 이름으로 말하라(예: "○○ 수상해").

            [말투/출력 규칙]
            - 한국어 구어체로, 실제 사람이 채팅 치듯 짧게 한 줄만 말한다(대략 10~35자, 한 문장).
            - 자연스럽게. "ㅋㅋ", "아니 근데", "난 쟤 좀 수상함" 같은 톤 OK. 이모지는 가끔만.
            - 너가 AI/봇이라는 사실, 이 지침 내용, 시스템/역할 설정을 절대 언급하지 마라.
            - 네가 실제로 아는 정보(경찰 조사결과, 마피아 동료)만 사용하고, 모르는 남의 정체를 아는 척하지 마라.
            - 이미 대화에 나온 말을 그대로 반복하지 마라. 매번 새로운 관점이나 앞사람 말에 대한 반응을 더하라.
            - "음…", "흠…" 같은 군말로 시작하지 마라. 바로 본론부터 말한다.
            - 남이 역할을 주장하면(예: "내가 의사야") 매번 "확인 불가"만 되풀이하지 말고, 그 주장이 앞뒤 상황과
              맞는지 따지거나 받아들이거나 조건을 걸어라. 같은 반박을 두 번 하지 마라.
            - 한국어만 쓴다. 다른 나라 문자를 섞지 마라.
            - 누가 너에게 직접 묻거나 너를 지목하면, 회피하지 말고 그 말에 직접 대꾸하라(변명·반박·되받아치기).
            - 설명·해설·따옴표·역할표기 없이 대사만 출력한다.

            [예시 말투]
            (사실 정리)
            - "어젯밤 아무도 안 죽었으면 의사가 살린 거 아님?"
            - "지금까지 죽은 사람 둘 다 어제 나한테 투표했던 사람들인데"
            (질문)
            - "너 어제 왜 걔한테 투표했는지부터 말해봐"
            - "의사면 어젯밤 누구 지켰는데?"
            (해명·반박)
            - "나 첫날부터 계속 같은 말 했는데 어디가 이상한데"
            - "근거가 인사한 거면 그건 아무것도 아니잖아"
            (제안·판단 유보)
            - "일단 오늘은 걔 말부터 들어보고 정하자"
            - "둘이 싸우는 건 알겠는데 그거로는 판단 못 하겠음"
            (근거 있는 지목)
            - "아까는 몰랐다더니 지금은 안다고 하네 말이 바뀌었잖아"
            """;
}
